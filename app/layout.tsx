import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const siteUrl = "https://antoniomorales.cl";
const title = "Antonio Morales | Desarrollador Web Fullstack";
const description =
  "Portfolio profesional de Antonio Morales, desarrollador web fullstack especializado en tecnologías modernas como React, Node.js y bases de datos relacionales y NoSQL.";

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title,
  description,
  openGraph: {
    title,
    description,
    url: siteUrl,
    siteName: "Antonio Morales",
    locale: "es_CL",
    type: "website",
  },
  twitter: {
    card: "summary_large_image",
    title,
    description,
  },
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="es" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  // Aplicar dark mode según localStorage o preferencia del sistema
                  document.documentElement.classList.toggle(
                    'dark',
                    localStorage.theme === 'dark' ||
                      (!('theme' in localStorage) &&
                       window.matchMedia('(prefers-color-scheme: dark)').matches)
                  );
                } catch (e) {}
              })();
            `,
          }}
        />
      </head>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        {children}
      </body>
    </html>
  );
}
